// ConvertEmoji converts a Slack emoji shortcode to Unicode emoji
// If the emoji is not found in the map, returns the original shortcode with colons
func ConvertEmoji(shortcode string) string {
	// Remove leading/trailing colons if present
	trimmed := strings.Trim(shortcode, ":")

	if emoji, ok := emojiMap[trimmed]; ok {
		return emoji
	}

	// Return original with colons if not found
	return ":" + trimmed + ":"
}

// ConvertEmojiInText converts all emoji shortcodes in a text string to Unicode emojis
// Example: "Hello :wave: :smile:" becomes "Hello 👋 😄"
func ConvertEmojiInText(text string) string {
	// Simple replacement - finds :word: patterns and converts them
	result := text
	start := 0

	for {
		// Find next emoji shortcode
		startIdx := strings.Index(result[start:], ":")
		if startIdx == -1 {
			break
		}
		startIdx += start

		// Find end of shortcode
		endIdx := strings.Index(result[startIdx+1:], ":")
		if endIdx == -1 {
			break
		}
		endIdx += startIdx + 1

		// Extract shortcode and convert
		shortcode := result[startIdx+1 : endIdx]
		if emoji, ok := emojiMap[shortcode]; ok {
			result = result[:startIdx] + emoji + result[endIdx+1:]
			start = startIdx + len(emoji)
		} else {
			start = endIdx + 1
		}
	}

	return result
}
